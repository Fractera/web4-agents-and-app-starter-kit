import type { ReactNode } from "react"
import type { Block, WorkspaceItem } from '@/lib/content/blocks/types'
import { type WorkspacePageData, wordsOf } from '@/lib/collection/types'
import { ArchitectPage } from './architect-page'
import { architectLayerUi } from '../_i18n/architect-layer.i18n'

// СТРАНИЦА КОЛЛЕКЦИИ — оболочка для страницы, которая живёт папкой (254).
//
// 🔒 ЧТО ОНА ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Она превращает ДАННЫЕ папки в блоки
// каталога и отдаёт их общей оболочке слоя. Второй раскладки здесь не заводится:
// `ArchitectPage` по-прежнему единственная, и всё, что она умеет, доступно и
// странице-папке.
//
// 🔒 СТРАНИЦА НАЗЫВАЕТ ТОЛЬКО СВОЮ ПАПКУ И ПАПКУ-РОДИТЕЛЯ. Адрес складывается
// здесь (`dir` + `meta.slug`), поэтому переименование раздела — это
// переименование папки, а не правка адреса в трёх местах.
//
// 🛑 ГРУППА ВЫВОДИТСЯ ИЗ АДРЕСА, А НЕ ПЕРЕДАЁТСЯ СТРАНИЦЕЙ. Переданная руками,
// она разошлась бы с местом папки на диске — и меню отметило бы не ту группу,
// ничего при этом не сломав.

export function CollectionPage({
  lang,
  dir,
  page,
  content,
  widget,
  hideTopics = false,
  tabs: tabsOverride,
}: {
  lang: string
  /** Адрес папки-родителя без языка, например `/architect/tools`. */
  dir: string
  page: WorkspacePageData
  /**
   * Содержимое из `_components/` этой страницы — работающая часть: островки,
   * таблицы, формы, разобранные в блоки каталога.
   *
   * 🔒 ПУСТО — ЭТО ЗАКОННЫЙ ОТВЕТ, А НЕ ОШИБКА (решение владельца 2026-09-19:
   * «компонент страницы может возвращать контент-заглушку, а может ничего не
   * возвращать, потому что сама страница должна иметь обработчик: если ничего не
   * пришло — вернуть просто название страницы с текстом "скоро будет
   * построена"»). Поэтому страница ЗАВЕРШЕНА с первой минуты: она существует,
   * открывается, называет себя и честно говорит о своём состоянии.
   */
  content?: Block[]
  /**
   * Собственный островок маршрута (271): вещь, которая живёт в папке маршрута, а не в каталоге видов
   * (комплект агента службы). Есть островок — третье состояние «скоро будет построено» не наступает.
   */
  widget?: ReactNode
  /**
   * Скрыть темы страницы и их ряд вкладок (324-1). Слово владельца 2026-09-27 о «Что меняет постоянный адрес» на «Активации
   * домена»: «он актуален до того как подключён первый домен сразу подключению скрывает этот текст он только путает».
   * Решает страница по состоянию узла; ряд вкладок скрывается вместе с темами — иначе он вёл бы на якоря, которых нет.
   */
  hideTopics?: boolean
  /**
   * Оглавление страницы, если его собирает сама страница (600-1, «Как это работает»: вкладка на раздел, якорь — заголовок h2).
   * Не задано — ряд строится из тем `_data`, как и прежде; у остальных страниц ничего не меняется.
   */
  tabs?: WorkspaceItem[]
}) {
  const ui = architectLayerUi(lang)
  const words = wordsOf(page, lang)
  const path = `${dir}/${page.meta.slug}`
  const topics = hideTopics ? [] : words.topics ?? []

  // Темы страницы: заголовок третьего уровня с явным якорем, текст, список.
  // Темы из `_data` — текст, который пишут словами.
  const fromTopics: Block[] = topics.flatMap((t): Block[] => [
    { kind: 'h3', text: t.title, id: t.anchor },
    { kind: 'p', text: t.text },
    ...(t.points ? [{ kind: 'list' as const, items: t.points }] : []),
  ])

  // 🔒 ТРИ СОСТОЯНИЯ СТРАНИЦЫ, И ТРЕТЬЕ — ПОЛНОЦЕННОЕ, А НЕ ПОЛОМКА.
  //
  //   1. есть работающая часть и/или темы → показываем и то, и другое;
  //   2. есть только одно из двух → показываем его;
  //   3. нет ни того, ни другого → страница называет себя и говорит, что
  //      содержимое скоро будет построено.
  //
  // Третье состояние — причина, по которой страница СЧИТАЕТСЯ ЗАВЕРШЁННОЙ в тот
  // момент, когда создана папка: она существует, открывается, стоит в меню и
  // честно сообщает о себе. ✗ Без обработчика пустоты на её месте была бы белая
  // страница, которую человек читает как поломку продукта.
  //
  // 🪦 ЗДЕСЬ СТОЯЛО `content.length > 0 ? content : fromTopics` — блоки И ТЕМЫ
  // БЫЛИ АЛЬТЕРНАТИВОЙ, и это оказалось дефектом, а не выбором (найден 264-2).
  //
  // ✗ ЧЕМ ОПЛАЧЕНО. У страницы «Активация домена» есть и лестница в
  // `_components/`, и пять тем в `_data`. Блоки побеждали — и весь текст тем
  // (зачем нужен постоянный адрес, порядок из пяти шагов, что делать без домена,
  // сколько это стоит) НЕ РЕНДЕРИЛСЯ ВООБЩЕ. Измерено на боевом узле: фразы
  // «Что меняет постоянный адрес» в отданном HTML — ноль.
  //
  // 🛑 И ВТОРАЯ ПОЛОВИНА, КОТОРАЯ ДЕЛАЕТ ЭТО ЯВНЫМ ДЕФЕКТОМ, А НЕ ВКУСОМ: ряд
  // вкладок строится из тем ВСЕГДА, независимо от этой ветки. То есть страница
  // печатала `href="#why"` на якорь, которого в разметке не было, — ссылка в
  // никуда. Ни типы, ни сборка такого не видят: оба состояния для них законны.
  //
  // 🔒 ПОРЯДОК: РАБОТАЮЩАЯ ЧАСТЬ, ПОТОМ ТЕКСТ. Человек приходит на страницу слоя
  // за действием, а не за чтением; текст объясняет то, что он уже видит. Нужен
  // обратный порядок — страница собирает всё сама в своём `_components/`, и эта
  // ветка ей не мешает.
  const built: Block[] = [...(content ?? []), ...fromTopics]
  const children: Block[] = built.length > 0 || widget ? built : [{ kind: 'note', text: ui.soon }]

  // Верхний ряд — навигация ПО ЭТОЙ странице. Тем нет — ряда нет вовсе, и это
  // законное состояние раздела, у которого ещё нет содержимого.
  const tabs: WorkspaceItem[] | undefined =
    tabsOverride ?? (topics.length > 0 ? topics.map((t) => ({ label: t.tab, href: `#${t.anchor}` })) : undefined)

  return (
    <ArchitectPage
      lang={lang}
      path={path}
      title={words.title}
      lead={words.lead}
      tabs={tabs}
      children={children}
      widget={widget}
    />
  )
}
